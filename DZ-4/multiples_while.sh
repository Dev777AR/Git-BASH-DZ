#!/bin/bash

# Инициализируем счётчик значением 1 (согласно логике подсказки)
count=1

# Цикл выполняется до тех пор, пока счётчик меньше или равен 10
while (( count <= 10 )); do
  # Выводим текущее значение счётчика, умноженное на 3
  echo $(( count * 3 ))
  
  # Увеличиваем значение счётчика на 1 для следующей итерации
  (( count++ ))
done

