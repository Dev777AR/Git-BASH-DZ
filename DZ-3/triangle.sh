#!/bin/bash

# Записываем три стороны треугольника из аргументов
a=$1
b=$2
c=$3

# Вычисляем полупериметр s и площадь через bc с поддержкой дробей
# Флаг -l подключает математическую библиотеку для работы sqrt()
area=$(echo "scale=1; s=($a+$b+$c)/2; sqrt(s*(s-$a)*(s-$b)*(s-$c))" | bc -l)

# Выводим результат
echo "Для сторон $a, $b и $c площадь треугольника равна $area."

