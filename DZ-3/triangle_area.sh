#!/bin/bash

# Записываем переданные аргументы в понятные переменные
base=$1
height=$2

# Вычисляем площадь по формуле: 0.5 * основание * высоту
# Используем bc с точностью scale=1 для вывода десятичной точки
area=$(echo "scale=1; 0.5 * $base * $height" | bc)

# Выводим результат
echo "Для основания $base и высоты $height площадь треугольника равна $area."

