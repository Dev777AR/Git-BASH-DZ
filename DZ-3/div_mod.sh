#!/bin/bash

# Запрашиваем ввод двух чисел у пользователя
echo -n "Введите первое (большее) число: "
read num1

echo -n "Введите второе (меньшее) число: "
read num2

# Вычисляем частное и остаток с помощью арифметического контекста
div=$(( num1 / num2 ))
mod=$(( num1 % num2 ))

# Выводим результат строго по условию задачи
echo "Для чисел $num1 и $num2 частное равно $div, а остаток — $mod."

