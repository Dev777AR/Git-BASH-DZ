#!/bin/bash

# Записываем переданные аргументы в понятные переменные
length=$1
width=$2

# Вычисляем площадь: произведение длины и ширины
area=$(( length * width ))

# Вычисляем периметр: удвоенная сумма длины и ширины
perimeter=$(( 2 * (length + width) ))

# Вывод результата строго по формату задания
echo "Для длины $length и ширины $width площадь должна быть $area, а периметр — $perimeter."

